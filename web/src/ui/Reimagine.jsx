// "See it in <year>": capture the 3D view, ask the server for a period photograph, compare them with a slider.
// The R3F <Canvas> needs gl={{ preserveDrawingBuffer: true }} or the capture comes back blank.
import { useEffect, useState } from 'react'
import { useStore } from '../store'
import './reimagine/reimagine.css'

const MODEL_FALLBACK = 'gpt-image-2.5-flare'

function capture() {
  const canvas = document.querySelector('canvas[data-engine]') || document.querySelector('canvas')
  if (!canvas) throw new Error('There is no 3D view to capture yet.')
  return canvas.toDataURL('image/jpeg', 0.92)
}

export default function Reimagine() {
  const year = useStore((s) => s.year)
  const [state, setState] = useState(null) // null | {before, year, status: 'busy'|'done'|'error', after?, model?, error?}
  const [split, setSplit] = useState(50)
  const [secs, setSecs] = useState(0)

  const run = async (before, y) => {
    setState({ before, year: y, status: 'busy' })
    setSecs(0)
    try {
      const r = await fetch('/api/reimagine', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ image: before, year: y }),
      })
      const j = await r.json().catch(() => ({}))
      if (!r.ok) throw new Error(typeof j.detail === 'string' ? j.detail : 'Something went wrong. Try again.')
      setState({ before, year: j.year, status: 'done', after: j.image, model: j.model })
      setSplit(50)
    } catch (e) {
      setState({ before, year: y, status: 'error', error: e.message || 'Something went wrong. Try again.' })
    }
  }

  const open = () => {
    try {
      run(capture(), year)
    } catch (e) {
      setState({ before: null, year, status: 'error', error: e.message })
    }
  }

  useEffect(() => {
    if (state?.status !== 'busy') return
    const t = setInterval(() => setSecs((s) => s + 1), 1000)
    return () => clearInterval(t)
  }, [state?.status])

  useEffect(() => {
    if (!state) return
    const onKey = (e) => e.key === 'Escape' && setState(null)
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [state])

  return (
    <>
      <button className="rm-open" onClick={open} disabled={state?.status === 'busy'}>
        See it in {year}
      </button>
      {state && (
        <div className="rm-backdrop" onClick={() => setState(null)}>
          <div className="rm-modal" role="dialog" aria-modal="true" aria-label={`The view in ${state.year}`} onClick={(e) => e.stopPropagation()}>
            <header className="rm-head">
              <h2>{state.year}</h2>
              <button className="rm-close" onClick={() => setState(null)} aria-label="Close">×</button>
            </header>

            <div className="rm-stage">
              {state.before && <img className="rm-img" src={state.before} alt="The 3D view" />}
              {state.status === 'done' && (
                <>
                  <img className="rm-img rm-after" src={state.after} alt={`The same view as a photograph in ${state.year}`} style={{ clipPath: `inset(0 0 0 ${split}%)` }} />
                  <div className="rm-divider" style={{ left: `${split}%` }} />
                  <span className="rm-tag rm-tag-l">3D view</span>
                  <span className="rm-tag rm-tag-r">{state.year}</span>
                  <input className="rm-range" type="range" min="0" max="100" value={split} onChange={(e) => setSplit(+e.target.value)} aria-label="Compare the 3D view with the photograph" />
                </>
              )}
              {state.status === 'busy' && (
                <div className="rm-veil" role="status">
                  <div className="rm-spinner" />
                  <p>Developing the photograph of {state.year}…</p>
                  <p className="rm-muted">{secs}s · this takes about 20 seconds</p>
                </div>
              )}
              {state.status === 'error' && (
                <div className="rm-veil" role="alert">
                  <p>{state.error}</p>
                  <button onClick={() => (state.before ? run(state.before, state.year) : open())}>Try again</button>
                </div>
              )}
            </div>

            <footer className="rm-foot">
              {state.status === 'done' ? `Generated by ${state.model || MODEL_FALLBACK} from this exact view.` : `Generated by ${MODEL_FALLBACK}.`}
              {state.status === 'done' && ' Drag to compare.'}
            </footer>
          </div>
        </div>
      )}
    </>
  )
}
